"""Generate the production environment file with fresh random secrets.

Hand-typed passwords are the usual way a "secured" deployment ends up with ``password123``.
This writes ``.env.prod`` (owner-only permissions) and the API key file Prometheus reads, and
refuses to overwrite either, because regenerating secrets under a live database would lock the
services out of their own data stores.
"""

from __future__ import annotations

import os
import re
import secrets
from dataclasses import dataclass
from pathlib import Path

# Hex only: safe inside URLs (the MongoDB connection string) and shells without any escaping.
SECRET_BYTES = 24

_HOSTNAME = re.compile(
    r"^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$|^[a-z0-9-]+(\.[a-z0-9-]+)*\.sslip\.io$"
)
_EMAIL = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")


_EXISTS = "{path} already exists; delete it first if you really want new secrets"


class EnvExists(RuntimeError):
    """The target file already exists; secrets are never regenerated silently."""


@dataclass(frozen=True)
class Generated:
    env_file: Path
    api_key_file: Path


def new_secret() -> str:
    return secrets.token_hex(SECRET_BYTES)


def render(domain: str, email: str, version: str) -> tuple[str, str]:
    """The .env.prod text and the API key it contains."""
    domain = domain.strip().lower()
    if not _HOSTNAME.match(domain):
        raise ValueError(f"{domain!r} is not a valid hostname (e.g. deltaflow.example.com)")
    if not _EMAIL.match(email):
        raise ValueError(f"{email!r} is not a valid email address")
    api_key = new_secret()
    text = f"""# Generated by `deltaflow gen-env`. Keep private; never commit.
DOMAIN={domain}
ACME_EMAIL={email}
DELTAFLOW_VERSION={version}

POSTGRES_USER=deltaflow
POSTGRES_DB=shop
POSTGRES_PASSWORD={new_secret()}
ELASTIC_PASSWORD={new_secret()}
MONGO_ROOT_USER=deltaflow
MONGO_ROOT_PASSWORD={new_secret()}

DELTAFLOW_API_KEY={api_key}
"""
    return text, api_key


def _write_new(path: Path, content: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # O_EXCL makes "refuse to overwrite" atomic, with no check-then-write race.
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, mode)
    except FileExistsError as exc:
        raise EnvExists(
            f"{path} already exists; delete it first if you really want new secrets"
        ) from exc
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(content)
    path.chmod(mode)  # umask can only remove bits at creation; make the final mode explicit


def generate(directory: Path, *, domain: str, email: str, version: str = "latest") -> Generated:
    env_file = directory / ".env.prod"
    key_file = directory / "secrets" / "prometheus_api_key"
    # Validate and check for collisions before writing anything, so a failure leaves no half set.
    text, api_key = render(domain, email, version)
    for path in (env_file, key_file):
        if path.exists():
            raise EnvExists(
                f"{path} already exists; delete it first if you really want new secrets"
            )
    _write_new(env_file, text, 0o600)
    key_file.parent.mkdir(parents=True, exist_ok=True)
    key_file.parent.chmod(0o700)
    # 0644, not 0600: the Prometheus container runs as an unprivileged user and must read it.
    # The 0700 directory is what keeps other host users out.
    _write_new(key_file, api_key, 0o644)
    return Generated(env_file, key_file)
